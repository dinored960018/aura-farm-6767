const DICT = { en, ko };
let lang = 'en';
try {
  const saved = localStorage.getItem('aura-lang');
  if (saved === 'ko' || saved === 'en') lang = saved;
} catch { /* 저장 안 되는 브라우저 */ }

export const getLang = () => lang;
// 저장된 선택이 없으면 포털이 알려 준 언어를 쓴다. 저장하지 않는다
export function suggestLang(locale) {
  let saved = null;
  try { saved = localStorage.getItem('aura-lang'); } catch { /* 무시 */ }
  if (!saved) lang = String(locale ?? '').toLowerCase().startsWith('ko') ? 'ko' : 'en';
}
export const ttsLang = () => (lang === 'ko' ? 'ko-KR' : 'en-US');

export function setLang(next) {
  lang = next === 'ko' ? 'ko' : 'en';
  try { localStorage.setItem('aura-lang', lang); } catch { /* 무시 */ }
}

export function t(key, vars) {
  let s = DICT[lang][key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function signLines(lines) {
  return lang === 'en' ? (SIGNS_EN[lines.join('|')] ?? lines) : lines;
}

// 화면에 고정된 글자들
export function applyStatic(root = document) {
  document.documentElement.lang = lang;
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml); // 위 사전의 내용만 넣는다
  for (const el of root.querySelectorAll('[data-i18n-ph]')) el.placeholder = t(el.dataset.i18nPh);
  for (const el of root.querySelectorAll('[data-i18n-title]')) {
    el.title = t(el.dataset.i18nTitle);
    if (el.hasAttribute('aria-label')) el.setAttribute('aria-label', el.title);
  }
}
